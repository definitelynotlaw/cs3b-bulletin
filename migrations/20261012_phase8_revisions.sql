CREATE TABLE announcement_revisions (
	id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
	announcement_id INT UNSIGNED NOT NULL,
	revision_number INT UNSIGNED NOT NULL,
	editor_id INT UNSIGNED NULL,
	title VARCHAR(200) NOT NULL,
	category VARCHAR(60) NOT NULL,
	caption TEXT NOT NULL,
	image_path VARCHAR(255) NULL,
	video_url VARCHAR(500) NULL,
	status ENUM('draft','scheduled','published') NOT NULL,
	publish_at DATETIME NULL,
	published_at DATETIME NULL,
	expires_at DATETIME NULL,
	event_date DATE NULL,
	event_start TIME NULL,
	event_end TIME NULL,
	event_all_day TINYINT(1) NOT NULL,
	deadline_date DATE NULL,
	deadline_time TIME NULL,
	deadline_all_day TINYINT(1) NOT NULL,
	is_pinned TINYINT(1) NOT NULL DEFAULT 0,
	tags_json TEXT NOT NULL,
	restore_from_revision_id BIGINT UNSIGNED NULL,
	created_at DATETIME NOT NULL,
	UNIQUE KEY uq_ann_revision (announcement_id, revision_number),
	KEY idx_ann_revision_created (announcement_id, created_at),
	CONSTRAINT fk_ann_revision_announcement FOREIGN KEY (announcement_id) REFERENCES announcements(id) ON DELETE CASCADE,
	CONSTRAINT fk_ann_revision_editor FOREIGN KEY (editor_id) REFERENCES users(id) ON DELETE SET NULL,
	CONSTRAINT fk_ann_revision_restore FOREIGN KEY (restore_from_revision_id) REFERENCES announcement_revisions(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;